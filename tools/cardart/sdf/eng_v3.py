def P3(x, y, z=0): return (Rr(x - 128), Y(y), Rr(z))
class B:
    def __init__(s): s.P = []; s.segs = {}
    def core(s, rows, mat='steel'): s.P.append(stack(rows, mat))
    def bell(s, rows, mat, step=4): s.P.append(bell(smooth_rows(rows, step), mat))
    def ring(s, y, r, th=2.4, mat='steel'): s.P.append(revolve([(0, Y(y + th / 2)), (Rr(r), Y(y + th / 2)), (Rr(r), Y(y - th / 2)), (0, Y(y - th / 2))], mat))
    def vcyl(s, x, y0, y1, r, z=0, mat='steel'): s.P.append(cyl(P3(x, (y0 + y1) / 2, z), Rr(r), Rr((y1 - y0) / 2), mat))
    def sph(s, x, y, r, z=0, mat='steel'): s.P.append(sphere(P3(x, y, z), Rr(r), mat))
    def pipe(s, pts, r, z=0, mat='steel'):
        q = [P3(p[0], p[1], p[2] if len(p) > 2 else z) for p in pts]
        s.segs.setdefault(mat, []).extend((a, b, Rr(r)) for a, b in zip(q, q[1:]))
    def fine(s, seed, y0, y1, rin, rout, n=10, rad=(1.1, 1.8)): s.segs.setdefault('steel', []).extend(plumbing(seed, y0, y1, env_fn(rin), env_fn(rout), n=n, rad=rad, fine=False))  # 가는 관을 더해 홀로그램 그림처럼 촘촘하게
    def done(s): return s.P + [Pipes(v, m) for m, v in s.segs.items()]

